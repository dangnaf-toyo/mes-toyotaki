create table if not exists public.sp_trong_luong (
  id             bigint generated always as identity primary key,
  ma_sp          text not null references public.master_products(ma_sp) on update cascade,
  ngay_can       date not null,
  trong_luong_kg numeric(10,6) not null check (trong_luong_kg > 0),
  ghi_chu        text,
  nguon          text not null default 'excel_20261111',
  created_at     timestamptz not null default now(),
  unique (ma_sp, ngay_can)
);
